"""
Tests for safe installer behavior around ~/.pymolpluginsrc.py.
"""

import os
import tempfile
import unittest

from pymol_ai_copilot.installer import (
    LEGACY_HEADER,
    MANAGED_END,
    MANAGED_START,
    update_plugin_rc,
)


class TestInstaller(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.rc_path = os.path.join(self.tmp.name, ".pymolpluginsrc.py")
        self.startup = os.path.join(self.tmp.name, ".pymol", "startup")

    def tearDown(self):
        self.tmp.cleanup()

    def _read(self):
        with open(self.rc_path, "r", encoding="utf-8") as f:
            return f.read()

    def test_preserves_existing_configuration(self):
        original = (
            "# user's own PyMOL configuration\n"
            "import pymol.plugins\n"
            "pymol.plugins.autoload = {'myplugin': 'myplugin.py'}\n"
        )
        with open(self.rc_path, "w", encoding="utf-8") as f:
            f.write(original)

        backup = update_plugin_rc(self.rc_path, self.startup)

        content = self._read()
        self.assertIn("myplugin", content)
        self.assertIn("autoload", content)
        self.assertIn(MANAGED_START, content)
        self.assertIn(MANAGED_END, content)
        self.assertIn(self.startup, content)
        self.assertIsNotNone(backup)
        self.assertTrue(os.path.exists(backup))
        with open(backup, "r", encoding="utf-8") as f:
            self.assertEqual(f.read(), original)

    def test_update_is_idempotent(self):
        update_plugin_rc(self.rc_path, self.startup)
        update_plugin_rc(self.rc_path, self.startup)
        content = self._read()
        self.assertEqual(content.count(MANAGED_START), 1)
        self.assertEqual(content.count(MANAGED_END), 1)

    def test_legacy_autogenerated_file_is_replaced(self):
        with open(self.rc_path, "w", encoding="utf-8") as f:
            f.write(
                LEGACY_HEADER + "\n"
                "import pymol.plugins\n"
                "pymol.plugins.autoload = {}\n"
            )

        update_plugin_rc(self.rc_path, self.startup)

        content = self._read()
        self.assertNotIn("autoload = {}", content)
        self.assertIn(MANAGED_START, content)

    def test_new_file_is_created(self):
        self.assertFalse(os.path.exists(self.rc_path))
        backup = update_plugin_rc(self.rc_path, self.startup)
        self.assertIsNone(backup)
        self.assertIn(self.startup, self._read())


if __name__ == "__main__":
    unittest.main()
