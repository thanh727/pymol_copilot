"""
Installer helpers for PyMOL AI Copilot.

The installer must never destroy a user's existing ``~/.pymolpluginsrc.py``.
Instead it appends an idempotent, clearly marked block and keeps a backup.
"""

import os
import shutil
import tempfile
from typing import Optional

MANAGED_START = "# >>> PyMOL AI Copilot managed block >>>"
MANAGED_END = "# <<< PyMOL AI Copilot managed block <<<"
LEGACY_HEADER = "# AUTOGENERATED FILE FOR PYMOL AI COPILOT"


def _managed_block(user_startup: str) -> str:
    escaped = user_startup.replace("\\", "\\\\").replace("'", "\\'")
    return "\n".join([
        MANAGED_START,
        "try:",
        "    from pymol import plugins",
        "    _copilot_paths = list(plugins.get_startup_path(True) or [])",
        f"    if '{escaped}' not in _copilot_paths:",
        f"        _copilot_paths.append('{escaped}')",
        "    plugins.set_startup_path(_copilot_paths, autosave=False)",
        "except Exception:",
        "    pass",
        MANAGED_END,
    ])


def _strip_managed_block(content: str) -> str:
    if MANAGED_START not in content or MANAGED_END not in content:
        return content
    before = content.split(MANAGED_START, 1)[0]
    after = content.split(MANAGED_END, 1)[1]
    return before.rstrip() + ("\n" if before.strip() else "") + after.lstrip()


def update_plugin_rc(rc_path: str, user_startup: str) -> Optional[str]:
    """
    Register ``user_startup`` in a PyMOL plugins rc file without clobbering it.

    Returns the backup path when an existing file was backed up, otherwise None.
    The write is atomic (temp file in the same directory + ``os.replace``).
    """
    rc_path = os.path.abspath(os.path.expanduser(rc_path))
    backup_path: Optional[str] = None
    existing = ""

    if os.path.exists(rc_path):
        with open(rc_path, "r", encoding="utf-8") as f:
            existing = f.read()

        backup_path = rc_path + ".copilot.bak"
        shutil.copy2(rc_path, backup_path)

        # Files created by the legacy installer were fully autogenerated, so it
        # is safe to replace them after taking a backup.
        if existing.lstrip().startswith(LEGACY_HEADER):
            existing = ""

    content = _strip_managed_block(existing)
    block = _managed_block(user_startup)
    if content.strip():
        new_content = content.rstrip() + "\n\n" + block + "\n"
    else:
        new_content = block + "\n"

    directory = os.path.dirname(rc_path) or "."
    fd, tmp_path = tempfile.mkstemp(
        prefix=".pymolpluginsrc.",
        suffix=".tmp",
        dir=directory,
        text=True,
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(new_content)
        os.chmod(tmp_path, 0o644)
        os.replace(tmp_path, rc_path)
    finally:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)

    return backup_path


def install_plugin(home: Optional[str] = None) -> bool:
    """Install the plugin symlink and register its startup path safely."""
    home_dir = os.path.expanduser(home) if home else os.path.expanduser("~")
    package_dir = os.path.dirname(os.path.abspath(__file__))

    print("=== Installing PyMOL AI Copilot ===")
    user_startup = os.path.join(home_dir, ".pymol", "startup")
    target_link = os.path.join(user_startup, "pymol_ai_copilot")
    os.makedirs(user_startup, exist_ok=True)

    # 1. Create or update symlink
    if os.path.islink(target_link) or os.path.exists(target_link):
        try:
            if os.path.islink(target_link):
                os.unlink(target_link)
            elif os.path.isdir(target_link):
                shutil.rmtree(target_link)
            else:
                os.remove(target_link)
        except Exception as e:
            print(f"! Notice: could not remove existing link '{target_link}': {e}")

    try:
        os.symlink(package_dir, target_link)
        print(f"✓ Linked {package_dir} -> {target_link}")
    except Exception as e:
        print(f"✗ Failed to create symlink: {e}")
        return False

    # 2. Register startup path through the official API when available.
    try:
        from pymol import plugins

        current_paths = list(plugins.get_startup_path(True) or [])
        if user_startup not in current_paths:
            current_paths.append(user_startup)
            plugins.set_startup_path(current_paths, autosave=True)
        print(f"✓ Registered '{user_startup}' in PyMOL plugins startup paths")
    except Exception as e:
        print(f"! Notice: Could not update PyMOL plugin paths via API ({e}).")
        rc_path = os.path.join(home_dir, ".pymolpluginsrc.py")
        try:
            backup = update_plugin_rc(rc_path, user_startup)
            if backup:
                print(f"✓ Backed up existing configuration to {backup}")
            print(f"✓ Merged startup path into {rc_path}")
        except Exception as write_error:
            print(f"✗ Failed to update {rc_path}: {write_error}")
            return False

    print("\n✓ Installation complete! PyMOL AI Copilot is now installed.")
    print("  To launch: Open PyMOL, click 'Plugin -> AI Copilot', or type 'ai_copilot' in the PyMOL prompt.")
    return True


def uninstall_plugin(home: Optional[str] = None) -> bool:
    """Remove the plugin symlink/copy from PyMOL's startup directory."""
    home_dir = os.path.expanduser(home) if home else os.path.expanduser("~")
    print("=== Uninstalling PyMOL AI Copilot ===")
    user_startup = os.path.join(home_dir, ".pymol", "startup")
    target_link = os.path.join(user_startup, "pymol_ai_copilot")

    if os.path.islink(target_link) or os.path.exists(target_link):
        try:
            if os.path.islink(target_link):
                os.unlink(target_link)
            else:
                shutil.rmtree(target_link)
            print(f"✓ Removed {target_link}")
        except Exception as e:
            print(f"✗ Failed to remove {target_link}: {e}")
            return False
    else:
        print("✓ Plugin link was not found.")

    print("✓ Uninstallation complete.")
    return True
