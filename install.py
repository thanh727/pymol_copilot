#!/usr/bin/env python3
"""
Installation and management script for PyMOL AI Copilot.
Registers the plugin in PyMOL's user startup folder and updates ~/.pymolpluginsrc.py.
"""

import argparse
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PACKAGE_DIR = os.path.join(SCRIPT_DIR, "pymol_ai_copilot")


def install_plugin():
    print("=== Installing PyMOL AI Copilot ===")
    user_startup = os.path.expanduser("~/.pymol/startup")
    target_link = os.path.join(user_startup, "pymol_ai_copilot")
    os.makedirs(user_startup, exist_ok=True)

    # 1. Create or update symlink
    if os.path.islink(target_link) or os.path.exists(target_link):
        try:
            os.remove(target_link)
        except Exception:
            pass

    try:
        os.symlink(PACKAGE_DIR, target_link)
        print(f"✓ Linked {PACKAGE_DIR} -> {target_link}")
    except Exception as e:
        print(f"✗ Failed to create symlink: {e}")
        return False

    # 2. Register startup path in PyMOL plugins configuration
    try:
        from pymol import plugins
        current_paths = plugins.get_startup_path(True)
        if user_startup not in current_paths:
            current_paths.append(user_startup)
            plugins.set_startup_path(current_paths, autosave=True)
        print(f"✓ Registered '{user_startup}' in PyMOL plugins startup paths")
    except Exception as e:
        print(f"! Notice: Could not automatically update PyMOL plugin paths via API ({e}).")
        # Fallback to direct writing to ~/.pymolpluginsrc.py
        rc_path = os.path.expanduser("~/.pymolpluginsrc.py")
        content = f"""# AUTOGENERATED FILE FOR PYMOL AI COPILOT
try:
  import pymol.plugins
  pymol.plugins.autoload = {{}}
  pymol.plugins.preferences = {{'instantsave': True, 'verbose': False}}
  pymol.plugins.set_startup_path(['{user_startup}'], False)
except Exception as e:
  pass
"""
        with open(rc_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"✓ Wrote fallback configuration to {rc_path}")

    print("\n✓ Installation complete! PyMOL AI Copilot is now installed.")
    print("  To launch: Open PyMOL, click 'Plugin -> AI Copilot', or type 'ai_copilot' in the PyMOL prompt.")
    return True


def uninstall_plugin():
    print("=== Uninstalling PyMOL AI Copilot ===")
    user_startup = os.path.expanduser("~/.pymol/startup")
    target_link = os.path.join(user_startup, "pymol_ai_copilot")

    if os.path.islink(target_link) or os.path.exists(target_link):
        try:
            if os.path.islink(target_link):
                os.unlink(target_link)
            else:
                import shutil
                shutil.rmtree(target_link)
            print(f"✓ Removed {target_link}")
        except Exception as e:
            print(f"✗ Failed to remove {target_link}: {e}")
            return False
    else:
        print("✓ Plugin link was not found.")

    print("✓ Uninstallation complete.")
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="PyMOL AI Copilot Installer")
    parser.add_argument("--uninstall", action="store_true", help="Uninstall the plugin")
    args = parser.parse_args()

    if args.uninstall:
        uninstall_plugin()
    else:
        install_plugin()
